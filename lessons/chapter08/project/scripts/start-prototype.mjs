import {existsSync} from 'node:fs';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
import {parseArgs} from 'node:util';
import {seedPrototype} from './prototype-seed.mjs';
const {values}=parseArgs({options:{db:{type:'string',default:'data/fanren/prototype.sqlite'},port:{type:'string',default:'4326'}}});
const db=resolve(values.db);
if(!existsSync(db))await seedPrototype(db);
const child=spawn(process.execPath,['dist/prototype-server.js','--db',db,'--port',values.port],{stdio:'inherit'});
child.once('exit',code=>{process.exitCode=code??1;});
